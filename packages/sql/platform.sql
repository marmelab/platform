-- Control plane data model (database "platform"). Idempotent: applied at every start.

create table if not exists users (
  id uuid primary key default gen_random_uuid(),
  email text not null unique,
  name text,
  role text not null default 'developer' check (role in ('admin', 'developer')),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists tokens (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references users (id) on delete cascade,
  name text not null,
  hash text not null unique,
  scopes text[] not null default '{}',
  app_ids uuid[],
  expires_at timestamptz,
  last_used_at timestamptz,
  revoked_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists apps (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique,
  name text not null,
  owner_id uuid not null references users (id),
  status text not null default 'provisioning'
    check (status in ('provisioning', 'running', 'stopped', 'error', 'deleted')),
  db_name text not null,
  secrets_enc text not null,
  error text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists app_members (
  app_id uuid not null references apps (id) on delete cascade,
  user_id uuid not null references users (id) on delete cascade,
  role text not null default 'collaborator' check (role in ('owner', 'collaborator')),
  primary key (app_id, user_id)
);

create table if not exists app_secrets (
  app_id uuid not null references apps (id) on delete cascade,
  name text not null,
  value_enc text not null,
  updated_at timestamptz not null default now(),
  primary key (app_id, name)
);

create table if not exists deployments (
  id uuid primary key default gen_random_uuid(),
  app_id uuid not null references apps (id) on delete cascade,
  kind text not null check (kind in ('frontend', 'functions', 'migrations')),
  version integer not null,
  status text not null default 'pending'
    check (status in ('pending', 'uploaded', 'live', 'ready', 'failed')),
  created_by uuid references users (id) on delete set null,
  created_at timestamptz not null default now(),
  finalized_at timestamptz,
  manifest jsonb,
  error text,
  unique (app_id, kind, version)
);

create table if not exists uploads (
  id uuid primary key default gen_random_uuid(),
  deployment_id uuid not null references deployments (id) on delete cascade,
  token_hash text not null unique,
  expires_at timestamptz not null,
  used_at timestamptz,
  size_bytes bigint,
  created_at timestamptz not null default now()
);

create table if not exists audit_log (
  id bigint generated always as identity primary key,
  user_id uuid references users (id) on delete set null,
  app_id uuid references apps (id) on delete set null,
  action text not null,
  details jsonb,
  created_at timestamptz not null default now()
);

-- Studio (M0ter): local passwords, browser sessions, numeric project id expected by Studio
alter table users add column if not exists password_hash text;
alter table apps add column if not exists studio_id integer generated by default as identity;

create table if not exists sessions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references users (id) on delete cascade,
  token_hash text not null unique,
  expires_at timestamptz not null,
  created_at timestamptz not null default now()
);

-- App roles: "developer" members became "collaborator" (bloc 1)
do $$
begin
  if exists (select 1 from pg_constraint where conname = 'app_members_role_check'
              and pg_get_constraintdef(oid) like '%developer%') then
    alter table app_members drop constraint app_members_role_check;
    update app_members set role = 'collaborator' where role = 'developer';
    alter table app_members add constraint app_members_role_check check (role in ('owner', 'collaborator'));
  end if;
end $$;
alter table app_members alter column role set default 'collaborator';

-- Deleting a user keeps their deployments and audit entries, without the author
do $$
begin
  if exists (select 1 from pg_constraint where conname = 'audit_log_user_id_fkey' and confdeltype <> 'n') then
    alter table audit_log drop constraint audit_log_user_id_fkey,
      add constraint audit_log_user_id_fkey foreign key (user_id) references users (id) on delete set null;
  end if;
  if exists (select 1 from pg_constraint where conname = 'deployments_created_by_fkey' and confdeltype <> 'n') then
    alter table deployments drop constraint deployments_created_by_fkey,
      add constraint deployments_created_by_fkey foreign key (created_by) references users (id) on delete set null;
  end if;
end $$;

-- M3bis: GitHub repository linked to the app (link_repo), releases (one per CI run or direct deployment)
alter table apps add column if not exists github_repo text;
alter table apps add column if not exists github_repo_id bigint;
alter table apps add column if not exists default_branch text;

create table if not exists releases (
  id uuid primary key default gen_random_uuid(),
  app_id uuid not null references apps (id) on delete cascade,
  -- ci: GitHub Actions run authenticated by OIDC; direct: PAT through MCP (admin exception when DIRECT_DEPLOY=admins)
  source text not null check (source in ('ci', 'direct')),
  status text not null default 'running' check (status in ('running', 'succeeded', 'failed')),
  commit_sha text,
  ref text,
  -- "<run_id>/<run_attempt>": one release per CI run attempt
  ci_run_id text,
  ci_run_url text,
  github_actor text,
  created_by uuid references users (id) on delete set null,
  admin_exception boolean not null default false,
  reason text,
  error text,
  started_at timestamptz not null default now(),
  finished_at timestamptz
);
create unique index if not exists releases_ci_run_key on releases (app_id, ci_run_id) where ci_run_id is not null;
create index if not exists releases_app_started on releases (app_id, started_at desc);

alter table deployments add column if not exists release_id uuid references releases (id) on delete set null;

-- Platform settings set at runtime (CLI set-setting), overriding the control plane's environment
create table if not exists settings (
  key text primary key,
  value text not null,
  updated_at timestamptz not null default now()
);

-- M4 phase 2: per-app load, sampled every minute by the control plane (metrics.ts) into the current hour.
-- requests and responses_5xx come from Caddy's access log (public app hosts), db_size_bytes from pg_database_size,
-- memory_bytes from Docker (the app's GoTrue and PostgREST containers; the shared edge runtime is not counted).
create table if not exists app_metrics (
  app_id uuid not null references apps (id) on delete cascade,
  hour timestamptz not null,
  requests bigint not null default 0,
  responses_5xx bigint not null default 0,
  db_size_bytes bigint,
  memory_bytes bigint,
  primary key (app_id, hour)
);
create index if not exists app_metrics_hour on app_metrics (hour);
-- last request seen in the access log (kept beyond the metrics retention, for the "abandoned" flag)
alter table apps add column if not exists last_request_at timestamptz;
-- last restore from a backup (A4): counts as activity for the "abandoned" flag; created_at keeps the original creation
alter table apps add column if not exists restored_at timestamptz;

-- Sampler state (one row): position in Caddy's access log, first sample (the abandoned flag waits for N days of data)
create table if not exists metrics_state (
  id integer primary key default 1 check (id = 1),
  log_inode text,
  log_offset bigint not null default 0,
  started_at timestamptz not null default now(),
  sampled_at timestamptz
);

-- M6: app auth policy set by configure_auth (app-auth.ts). No row: the defaults (sign-up on, email confirmation when
-- the platform has an SMTP, any email domain, the app's own URL only, the app's name and the platform sender).
create table if not exists app_auth_config (
  app_id uuid primary key references apps (id) on delete cascade,
  signup_enabled boolean not null default true,
  email_confirmation boolean not null default true,
  allowed_email_domains text[] not null default '{}',
  redirect_urls text[] not null default '{}',
  sender_name text,
  sender_email text,
  updated_by uuid references users (id) on delete set null,
  updated_at timestamptz not null default now()
);

-- M6, A6: when the owners were emailed that the app is abandoned; cleared when the app is active again, so that the
-- next abandonment is notified once more
alter table apps add column if not exists abandoned_notified_at timestamptz;

-- M6 part 2, platform company SSO (A7, sso.ts): the IdP identity linked to an account at its first SSO login (by
-- verified email), so that a later login with the same email but another subject is refused
alter table users add column if not exists sso_issuer text;
alter table users add column if not exists sso_subject text;
create unique index if not exists users_sso_identity on users (sso_issuer, sso_subject) where sso_subject is not null;

-- M6 part 2, company SSO for an app's users (U2, app-sso.ts): 'company' adds the platform's OIDC provider to the app's
-- GoTrue as the custom provider "custom:company"
alter table app_auth_config add column if not exists sso_provider text;
do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'app_auth_config_sso_provider_check') then
    alter table app_auth_config add constraint app_auth_config_sso_provider_check check (sso_provider in ('company'));
  end if;
end $$;

-- M7, A4: backups of the apps (backups.ts). One row per backup attempt: scheduled (daily), manual (create_backup, the
-- admin console, the CLI), pre_restore (taken by a restore before it replaces the app's data) and final (delete_app,
-- B8). location: the backup's directory on the backups volume, or s3://<bucket>/<key prefix>/ when the S3 target is
-- configured. app_id is null once the app is deleted: the slug stays (a deleted app is restored from its slug).
create table if not exists backups (
  id uuid primary key default gen_random_uuid(),
  app_id uuid references apps (id) on delete set null,
  slug text not null,
  kind text not null check (kind in ('scheduled', 'manual', 'pre_restore', 'final')),
  status text not null default 'running' check (status in ('running', 'succeeded', 'failed')),
  started_at timestamptz not null default now(),
  finished_at timestamptz,
  size_bytes bigint,
  location text,
  -- file name -> size in bytes
  files jsonb,
  -- the backup's manifest.json (no secret)
  manifest jsonb,
  error text,
  created_by uuid references users (id) on delete set null
);
create index if not exists backups_slug_started on backups (slug, started_at desc);
create index if not exists backups_app_started on backups (app_id, started_at desc);
create index if not exists backups_status_started on backups (status, started_at desc);

-- Scheduler state (one row): the UTC day whose scheduled run was claimed (one run per day across processes), and the
-- last run's summary
create table if not exists backup_state (
  id integer primary key default 1 check (id = 1),
  scheduled_on date,
  run_started_at timestamptz,
  run_finished_at timestamptz,
  run_summary jsonb
);

-- M7 part 2, security linter (PLAN_1 §7 and §8, lint.ts): every run of the linter on an app, with its results. Runs
-- come from a committed migrations batch (source 'migrations', with its release), the admin console or the CLI
-- ('manual'), the periodic sweep ('scheduled', catches schema changes made outside releases) and the platform upgrade
-- ('upgrade'). lints: [{name, level, object, detail}]; error: the run itself failed (database unreachable...).
create table if not exists lint_runs (
  id uuid primary key default gen_random_uuid(),
  app_id uuid not null references apps (id) on delete cascade,
  release_id uuid references releases (id) on delete set null,
  source text not null check (source in ('migrations', 'manual', 'scheduled', 'upgrade')),
  ran_at timestamptz not null default now(),
  errors integer not null default 0,
  warnings integer not null default 0,
  infos integer not null default 0,
  lints jsonb not null default '[]'::jsonb,
  error text
);
create index if not exists lint_runs_app_ran on lint_runs (app_id, ran_at desc);

-- M7 part 2, platform version (A8, version.ts): one row per version the control plane started with (VERSION file of
-- the image), with the images of the platform's containers at that time. The latest row is the running version.
create table if not exists platform_versions (
  id bigint generated always as identity primary key,
  version text not null,
  started_at timestamptz not null default now(),
  components jsonb not null default '{}'::jsonb
);

-- Browser sign-in for Claude Code (OAuth, oauth.ts and platform-auth.ts): one table for every credential the MCP
-- endpoint accepts. kind 'pat': personal access token (hash of the value). 'oauth': a Claude Code connection, i.e. one
-- session of the platform's GoTrue (auth.sessions, in this database) opened by an OAuth client; its access tokens are
-- GoTrue JWTs, not stored (hash null). 'deploy': short-lived token minted by create_deploy_token, restricted to one app
-- (app_ids) and to the publishing tools (scopes = {deploy}), child of the credential that minted it (parent_id).
alter table tokens add column if not exists kind text not null default 'pat';
do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'tokens_kind_check') then
    alter table tokens add constraint tokens_kind_check check (kind in ('pat', 'oauth', 'deploy'));
  end if;
end $$;
alter table tokens alter column hash drop not null;
alter table tokens add column if not exists oauth_session_id uuid unique;
alter table tokens add column if not exists oauth_client_id uuid;
alter table tokens add column if not exists parent_id uuid references tokens (id) on delete cascade;
