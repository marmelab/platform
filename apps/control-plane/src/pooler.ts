// Connection pooler (README.md, "Connection pooler"): one PgBouncer in transaction mode in front of every app database.
// PostgREST (app_<id>_authenticator) and Storage (app_<id>_storage_admin, its tenant `databasePoolUrl`) connect
// through it; GoTrue, Realtime, the owner role (migrations, Studio, edge functions) and the platform connect directly.
//
// Its static settings are deploy/pooler/pgbouncer.ini; its [databases] entries, one per app, are generated here from
// the apps table into a file of the volume shared with the pooler (%include), then applied with RELOAD through the
// admin console. Clients authenticate with their own role (auth_query, packages/sql poolerAuthSql).
import { appRoles } from "@platform/sql";
import pg from "pg";
import { dbId } from "./apps.ts";
import { config } from "./config.ts";
import { many } from "./db.ts";
import { writeFileAtomic } from "./fsutil.ts";

/** URL of an app database through the pooler, for one of the pooled roles. */
export const poolerUrl = (user: string, password: string, database: string) =>
  `postgres://${user}:${password}@${config.pooler.host}:${config.pooler.port}/${database}`;

/** Runs admin console commands (simple query protocol only: no parameters). */
async function adminConsole(commands: string[]) {
  const client = new pg.Client({
    host: config.pooler.host,
    port: config.pooler.port,
    user: config.pooler.adminUser,
    password: config.pooler.adminPassword,
    database: "pgbouncer",
    connectionTimeoutMillis: 5000,
  });
  await client.connect();
  try {
    for (const command of commands) await client.query(command);
  } finally {
    await client.end().catch(() => {});
  }
}

/** The [databases] entries of every app that still has a database. */
export function databasesIni(slugs: string[]) {
  const lines = slugs.map((slug) => {
    const database = appRoles(dbId(slug)).database;
    return `${database} = host=${config.pg.host} port=${config.pg.port} dbname=${database} ` +
      `max_db_connections=${config.pooler.maxDbConnections}`;
  });
  return `; generated by the control plane (pooler.ts), do not edit\n${lines.join("\n")}\n`;
}

let queue: Promise<unknown> = Promise.resolve();

/**
 * Writes the entries of every app (running, stopped or in error) and reloads the pooler. Idempotent, serialized. The
 * pooler may still be starting at control plane start: the file is written anyway, and read when it starts.
 */
export function syncPooler(): Promise<void> {
  const next = queue.then(async () => {
    const apps = await many<{ slug: string }>("select slug from apps where status <> 'deleted' order by slug");
    await writeFileAtomic(config.pooler.databasesFile, databasesIni(apps.map((a) => a.slug)), 0o644);
    await adminConsole(["RELOAD"]);
  });
  queue = next.catch(() => undefined);
  return next;
}

/**
 * Closes the app's client and server connections in the pooler (delete_app, before DROP DATABASE). Best effort: a
 * database unknown to the pooler, or a pooler that is down, is not an error (DROP DATABASE ... WITH (FORCE)
 * terminates the server connections anyway).
 */
export async function killPoolerDatabase(slug: string) {
  try {
    await adminConsole([`KILL ${appRoles(dbId(slug)).database}`]);
  } catch (error) {
    if (!/no such database/i.test(String(error))) console.error(`pooler KILL of ${slug} failed`, error);
  }
}
